const EVO_EN_ES = Object.fromEntries(Object.entries(EVO_ES_EN).map(([es,en]) => [en,es]));
let evoLanguage = 'es';

function evoTranslateValue(value, language) {
  const text = String(value || '');
  const trimmed = text.trim();
  if (!trimmed) return text;
  const table = language === 'en' ? EVO_ES_EN : EVO_EN_ES;
  const translated = table[trimmed];
  if (!translated) return text;
  const leading = text.match(/^\s*/)[0];
  const trailing = text.match(/\s*$/)[0];
  return leading + translated + trailing;
}
function evoTranslateNode(root, language) {
  if (!root) return;
  if (root.nodeType === Node.TEXT_NODE) {
    const parent = root.parentElement;
    if (parent && !/^(SCRIPT|STYLE|CODE)$/i.test(parent.tagName)) {
      const translated = evoTranslateValue(root.nodeValue, language);
      if (translated !== root.nodeValue) root.nodeValue = translated;
    }
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) return;
  if (root.nodeType === Node.ELEMENT_NODE) {
    ['placeholder','title','aria-label'].forEach(attribute => {
      if (root.hasAttribute(attribute)) root.setAttribute(attribute, evoTranslateValue(root.getAttribute(attribute), language));
    });
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (parent && !/^(SCRIPT|STYLE|CODE)$/i.test(parent.tagName)) {
      const translated = evoTranslateValue(node.nodeValue, language);
      if (translated !== node.nodeValue) node.nodeValue = translated;
    }
  }
}
function evoSetLanguage(language, remember = true) {
  evoLanguage = language === 'en' ? 'en' : 'es';
  document.documentElement.lang = evoLanguage;
  evoTranslateNode(document.body, evoLanguage);
  document.title = evoTranslateValue(document.title, evoLanguage);
  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = evoTranslateValue(description.content, evoLanguage);
  const selector = document.getElementById('languageSelect');
  if (selector) selector.value = evoLanguage;
  if (remember) localStorage.setItem('evo-language', evoLanguage);
}
