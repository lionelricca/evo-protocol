const evoLanguageObserver = new MutationObserver(mutations => {
  for (const mutation of mutations) {
    if (mutation.type === 'characterData') evoTranslateNode(mutation.target, evoLanguage);
    mutation.addedNodes.forEach(node => evoTranslateNode(node, evoLanguage));
  }
});
evoLanguageObserver.observe(document.body, { childList:true, subtree:true, characterData:true });
